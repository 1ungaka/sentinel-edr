#!/usr/bin/env bash
#
# clean-manifest.sh — label a directory tree as a specificity corpus.
#
# Emits a manifest.json that marks every regular file under a root as `clean`,
# so `cau eval` can measure the engine's specificity — false positives and,
# with the near-miss metric, how close benign files came to firing — over a
# real population (e.g. a Kali install). The population is the user's machine,
# not reproducible bytes, so no sha256 is recorded: this manifest measures the
# false-positive side, which needs no hashes, not recall.
#
# Usage:
#   scripts/clean-manifest.sh <root> [> corpus/local/specificity.json]
#
# Requires: find, jq (>= 1.7 for NUL-delimited input).

set -euo pipefail

root="${1:-}"
[ -n "$root" ] || { echo "usage: $0 <root>" >&2; exit 1; }
[ -d "$root" ] || { echo "not a directory: $root" >&2; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "need jq on PATH" >&2; exit 1; }

root="$(cd "$root" && pwd)"

find "$root" -type f -print0 \
  | jq -Rs --arg root "$root" '
      { schema_version: "1",
        name: "specificity",
        description: ("Specificity corpus: every file under " + $root + " labelled clean. Generated by scripts/clean-manifest.sh; measures false positives and near misses, not recall."),
        root: $root,
        defaults: { label: "clean", source: "local", license: "unknown" },
        samples: [ splits("\u0000") | select(length > 0) | ltrimstr($root + "/") | { id: ., path: . } ]
      }
    '
